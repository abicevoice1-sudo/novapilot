"""Persistence protocol for tasks. The API service implements this with SQLAlchemy;
tests use an in-memory implementation. The core never touches the DB directly."""

from __future__ import annotations

from typing import Protocol


class TaskStore(Protocol):
    async def create(
        self, goal: str, model: str | None, thread_id: str, source: str | None = None
    ) -> str: ...
    async def update(self, task_id: str, **fields) -> None: ...
    async def get(self, task_id: str) -> dict | None: ...
    async def list(self, limit: int = 50) -> list[dict]: ...
    async def add_event(self, task_id: str, type: str, payload: dict) -> None: ...
    async def events(self, task_id: str, after_id: int = 0) -> list[dict]: ...
